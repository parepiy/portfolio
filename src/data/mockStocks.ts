function generatePriceHistory(endPrice: number, days = 90) {
  const history = [];
  const now = new Date();
  let price = endPrice * (0.82 + Math.random() * 0.12);

  for (let i = days; i >= 0; i--) {
    const date = new Date(now);
    date.setDate(date.getDate() - i);
    if (i === 0) {
      price = endPrice;
    } else {
      const drift = ((endPrice - price) / i) * 0.35;
      const noise = (Math.random() - 0.5) * price * 0.022;
      price = Math.max(price + drift + noise, price * 0.5);
    }
    history.push({
      date: date.toISOString().split("T")[0],
      price: Math.round(price * 100) / 100,
      volume: Math.floor(Math.random() * 50_000_000 + 20_000_000),
    });
  }
  return history;
}

